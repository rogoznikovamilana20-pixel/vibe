-- СИМПТОМ: уведомления (FCM) приходят, но в открытом чате нет сообщений.
-- ПРИЧИНА: колонки profiles.fcm_token и profiles.phone были добавлены
--   ALTER TABLE ПОСЛЕ первоначального GRANT, поэтому у роли authenticated
--   не было прав SELECT на них. Любой запрос `select=*` / `profiles!sender_id(*)`
--   (используется в backend.listMessages) падал с
--   «permission denied for table profiles» -> список сообщений пуст.
--   FCM-уведомления приходят через service_role (обходит RLS/графты), поэтому
--   сами сообщения в БД есть, но клиент их не читает.
-- ФИКС: дать authenticated SELECT на эти колонки (row-level доступ по-прежнему
--   ограничен RLS-политиками profiles/messages/chats).

GRANT SELECT (fcm_token, phone) ON public.profiles TO authenticated;

